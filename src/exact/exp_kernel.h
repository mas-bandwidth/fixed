// e^(a * 2^-16) = *mantissa * 2^(*exponent - 126), *mantissa in [2^126, 2^127), for
// |a| <= 2^22 (|x| <= 64). |*mantissa * 2^-126 - e^r * 2^(j/128)| <= 2^-101.67
// (docs/design/transcendentals.md, section 1.1). Integer only.
//
// Budget table (docs/design/transcendentals.md, section 1.1), absolute on M in [1, 2):
//   ln 2 to 128 bits: |N| * 2^-129 / 128 on r, times M <= 2 -> 2^-122.44
//   r truncated to Q0.128, times 2 -> 2^-127
//   kernel, Sollya supnorm, times T_j < 2 -> 2^-101.67
//   Horner truncations (8 steps, each < 2^-127, damped by r < 2^-7.5), times 2 -> 2^-124
//   T_j rounding 2^-127, times P < 1.006 -> 2^-126.99
//   T_j * P truncated to Q2.126 -> 2^-126
//   sum on M -> 2^-101.67
//
// Regenerate the pasted digits with:  sollya sollya/exp_kernel.sollya
// (the T_j and C_k values below are the `T j hi lo` and `C_k` lines of sollya/exp_kernel.out).

// LN2_128 = round(ln2 * 2^128) = 235865763225513294137944142764154484399.
// fixed-exp-negative-control overrides these two macros; nothing else here is overridable.
#ifndef FIX_EXP_LN2_128_HI
#define FIX_EXP_LN2_128_HI UINT64_C(12786308645202655659)
#endif
#ifndef FIX_EXP_LN2_128_LO
#define FIX_EXP_LN2_128_LO UINT64_C(14547668686819489455)
#endif

static inline fixUInt128 fixExactMulHi128(fixUInt128 a, fixUInt128 b)
{
    fixUInt256 lo = fixUInt256MulU128ByU64(a, fixUInt128Lo(b));
    fixUInt256 hi = fixUInt256MulU128ByU64(a, fixUInt128Hi(b));
    lo = fixUInt256Add(lo, fixUInt256Shl(hi, 64));
    return lo.hi;
}

typedef struct
{
    uint64_t hi;
    uint64_t lo;
} fixExpKernelU128;

