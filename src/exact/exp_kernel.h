static inline void fixExpKernel(int64_t a, fixUInt128* mantissa, int* exponent)
{
    int sign = a < 0 ? -1 : 1;
    uint64_t absRaw = a < 0 ? (uint64_t)(-a) : (uint64_t)a;

    // N0 = sign * ((|raw| * INV_LN2_63) >> 72); INV_LN2_63 = round(2^63 / ln2).
    fixUInt128 prod = fixUInt128MulU64(absRaw, UINT64_C(13306513097844322492));
    uint64_t n0Mag = fixUInt128Lo(fixUInt128Shr(prod, 72));
    int64_t N = sign * (int64_t)n0Mag;

    fixUInt256 a256;
    if (a >= 0)
        a256 = fixUInt256Shl(fixUInt256FromU64(absRaw), 119);
    else
        a256 = fixUInt256Neg(fixUInt256Shl(fixUInt256FromU64(absRaw), 119));

    uint64_t n0Abs = N < 0 ? (uint64_t)(-N) : (uint64_t)N;
    fixUInt256 b256 = fixUInt256MulU128ByU64(
        fixUInt128Make(FIX_EXP_LN2_128_HI, FIX_EXP_LN2_128_LO), n0Abs);
    if (N < 0) b256 = fixUInt256Neg(b256);

    fixUInt256 D = fixUInt256Sub(a256, b256);

    fixUInt256 ln2_256 = fixUInt256FromU128(
        fixUInt128Make(FIX_EXP_LN2_128_HI, FIX_EXP_LN2_128_LO));

    if (fixInt256IsNegative(D))
    {
        D = fixUInt256Add(D, ln2_256);
        N -= 1;
    }
    if (fixUInt256Ge(D, ln2_256))
    {
        D = fixUInt256Sub(D, ln2_256);
        N += 1;
    }

    fixUInt128 r128 = fixUInt128Shr(D.lo, 7);
    int m = (int)(N >> 7);
    int j = (int)(N & 127);

    fixUInt128 tj = fixUInt128Make(FIX_EXP_T[j].hi, FIX_EXP_T[j].lo);

    fixUInt128 q = fixUInt128Make(FIX_EXP_C[6].hi, FIX_EXP_C[6].lo);
    {
        int k;
        for (k = 5; k >= 0; --k)
        {
            fixUInt128 h = fixExactMulHi128(q, r128);
            q = fixUInt128Add(fixUInt128Make(FIX_EXP_C[k].hi, FIX_EXP_C[k].lo), h);
        }
    }
    fixUInt128 two127 = fixUInt128Make(UINT64_C(0x8000000000000000), 0);
    fixUInt128 s = fixUInt128Add(two127, fixExactMulHi128(q, r128));
    fixUInt128 P = fixUInt128Add(two127, fixExactMulHi128(s, r128));
    fixUInt128 M = fixUInt128Shl(fixExactMulHi128(tj, P), 1);

    *mantissa = M;
    *exponent = m;
}

