// Correctly rounded ln, log2 and log10 for positive Q48.16 inputs, per
// docs/design/transcendentals.md sections 2.1, 2.2 and 2.3.
//
// Note on the kernel. The sibling card fixed-log-kernel is named as landed before this
// one and was expected to provide src/exact/log_kernel.h with fixLogKernel, which this
// file would include (never copy). That header is not present in this checkout (git log
// shows the last landed sibling is fixed-tanh-sollya), so the reduction, table and kernel
// are implemented here directly from the design and the committed Sollya numbers in
// sollya/log_kernel.out. This is the whole of what the kernel header would have held, and
// it is deliberately kept private to this file.
//
// Integer only, through the fixUInt128 / fixInt128 / fixUInt256 vocabulary, so the
// native and emulated 128-bit arms and gcc and clang give the same bits, and plain MSVC
// (no __int128) builds it.

